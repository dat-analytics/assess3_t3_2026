# Convert ZID strings to numeric values for seeding
# Remove 'z' prefix and convert to integer
zid_numbers <- as.integer(gsub("z", "", zids))

# Function to extract numeric part and generate seed
get_seed <- function(zid_string) {
  as.integer(gsub("z", "", zid_string))
}

# Loop through each ZID and generate the data file
for (i in seq_along(zids)) {
  zid <- zids[i]
  seed_value <- zid_numbers[i]
  
  # Set seed
  set.seed(seed_value)
  
  # Sample data
  ds <- dt[sample(nrow(dt), 3500, replace = FALSE), ]
  
  # Create filename
  filename <- paste0(zid, "_", zid, "-Assessment3Data.csv")
  
  # Write CSV
  write.csv(ds, filename, row.names = FALSE)
  
  # Progress indicator (every 50 files)
  if (i %% 50 == 0) {
    cat(paste("Processed", i, "of", length(zids), "files\n"))
  }
}

cat(paste("Done! Generated", length(zids), "CSV files\n"))
